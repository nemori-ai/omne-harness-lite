/// <reference lib="dom" />
import type { ArchitectureView, RelationKind, ViewEdge, ViewNode, ViewSelection } from './view.ts'
import type { selectArchitectureView } from './view.ts'

/** Embedded after TypeScript erasure. Only the supplied projection function crosses this boundary. */
export function architectureBrowser(selectView: typeof selectArchitectureView): void {
  const required = (id: string): HTMLElement => {
    const element = document.getElementById(id)
    if (element === null) throw new Error(`Missing architecture element ${id}`)
    return element
  }
  const select = (id: string): HTMLSelectElement => {
    const element = required(id)
    if (!(element instanceof HTMLSelectElement)) throw new Error(`Expected select ${id}`)
    return element
  }
  const checkbox = (id: string): HTMLInputElement => {
    const element = required(id)
    if (!(element instanceof HTMLInputElement)) throw new Error(`Expected input ${id}`)
    return element
  }
  // This JSON is generated by the typed renderer, not an accepted external upload.
  const graph: ArchitectureView = JSON.parse(required('architecture-data').textContent ?? '')
  const group = select('arch-group'),
    focus = select('arch-focus'),
    changes = select('arch-changes')
  const neighbors = checkbox('arch-neighbors'),
    complexity = checkbox('arch-complexity'),
    coupling = checkbox('arch-coupling')
  const diagram = required('arch-diagram'),
    detail = required('arch-detail'),
    list = required('arch-relations')
  const nodeById = new Map(graph.nodes.map(node => [node.id, node]))
  const relations = new Map<RelationKind, HTMLInputElement>()
  const element = (tag: string, text = '', className = ''): HTMLElement => {
    const el = document.createElement(tag)
    el.textContent = text
    el.className = className
    return el
  }
  const button = (text: string, action: () => void): HTMLButtonElement => {
    const el = document.createElement('button')
    el.textContent = text
    el.type = 'button'
    el.addEventListener('click', action)
    return el
  }
  const option = (value: string, text: string): HTMLOptionElement => {
    const el = document.createElement('option')
    el.value = value
    el.textContent = text
    return el
  }
  const svgElement = (tag: string, attrs: Record<string, string>, text?: string): SVGElement => {
    const el = document.createElementNS('http://www.w3.org/2000/svg', tag)
    for (const [key, value] of Object.entries(attrs)) el.setAttribute(key, value)
    if (text !== undefined) el.textContent = text
    return el
  }
  const kindLabel = {
    member: '组件 / 包',
    service: '服务键 · 静态同名',
    event: '事件名 · 静态同名',
    external: '外部代码依赖',
    group: '目录聚合',
  }
  const nodeKind = (node: ViewNode): string =>
    node.category === 'development' ? '开发成员' : kindLabel[node.kind]
  const changeLabel = { present: '', added: '新增', removed: '已删除 · BASE' }
  const scopeText = `HEAD ${graph.source.commit} · ${graph.source.kind} · dirty ${graph.source.dirty} / inputDirty ${graph.source.inputDirty}`
  required('arch-coordinate').textContent =
    scopeText +
    (graph.baseline === undefined
      ? ' · 无架构差分基线'
      : ` · 架构精确 BASE ${graph.baseline.commit}`)
  required('arch-counts').textContent =
    `产品成员 ${graph.document.current.scope.productMembers.length} · 静态事实 ${graph.document.current.facts.length} · 具体未知 ${graph.document.current.unknown.length}`
  required('arch-measurement').textContent =
    `圈复杂度算法 functionMetrics · 色带来源 ${graph.measurement.configSource} · 无函数表示无测量单元，覆盖率未提供；颜色不表示架构符合性。`
  group.append(
    option('', '系统总览'),
    ...graph.groups.map(node => option(node.group ?? '', node.label)),
  )
  focus.append(
    option('', '不聚焦'),
    ...graph.nodes
      .filter(node => node.kind !== 'external')
      .map(node =>
        option(
          node.id,
          `${nodeKind(node)} · ${node.member ?? node.label}${changeLabel[node.change] === '' ? '' : ' · ' + changeLabel[node.change]}`,
        ),
      ),
  )
  if (graph.baseline === undefined) {
    for (const child of changes.options) if (child.value !== 'current') child.disabled = true
  }
  for (const [key, label] of Object.entries(graph.relations)) {
    const input = document.createElement('input')
    input.type = 'checkbox'
    input.checked = true
    const relation = key as RelationKind
    relations.set(relation, input)
    const el = element('label')
    el.append(input, ` ${label}`)
    required('arch-kinds').append(el)
    input.addEventListener('change', render)
  }
  const selection = (): ViewSelection => {
    const value = changes.value
    if (!['current', 'all', 'added', 'removed', 'changed'].includes(value))
      throw new Error('Invalid change selection')
    return {
      group: group.value,
      focus: focus.value,
      neighbors: neighbors.checked,
      changes: value as ViewSelection['changes'],
      relations: [...relations].filter(([, input]) => input.checked).map(([key]) => key),
      complexity: complexity.checked,
      coupling: coupling.checked,
    }
  }
  let shown = selectView(graph, selection())
  function download(name: string, content: string, type: string): void {
    const url = URL.createObjectURL(new Blob([content], { type }))
    const link = document.createElement('a')
    link.download = name
    link.href = url
    link.click()
    setTimeout(() => URL.revokeObjectURL(url), 1000)
  }
  function showMetrics(member?: string): void {
    required('architecture-pane').hidden = true
    required('metrics-pane').hidden = false
    window.dispatchEvent(new Event('resize'))
    if (member !== undefined)
      window.dispatchEvent(new CustomEvent('architecture-member', { detail: member }))
  }
  function showArchitecture(): void {
    required('metrics-pane').hidden = true
    required('architecture-pane').hidden = false
  }
  function focusNode(node: ViewNode): void {
    if (node.kind === 'group') {
      group.value = node.group ?? ''
      focus.value = ''
    } else focus.value = node.id
    render()
    showNode(node)
  }
  function showNode(node: ViewNode): void {
    detail.replaceChildren(
      element('h2', node.member ?? node.label),
      element(
        'p',
        `${nodeKind(node)} · ${changeLabel[node.change] || '静态源码声明'}。服务/事件同名聚合不表示实际绑定。`,
      ),
    )
    if (node.kind === 'group') {
      detail.append(
        element('p', '依据 workspace 清单及路径聚合。目录组不表示运行、部署、事务或租户边界。'),
      )
      return
    }
    if (node.complexity !== undefined)
      detail.append(
        element(
          'p',
          node.complexity.functions === 0
            ? '无函数测量单元；成员仍存在。'
            : `函数 ${node.complexity.functions} · 最大 CC ${node.complexity.max} · CC 风险值 ${node.complexity.risk}`,
        ),
      )
    if (node.member !== undefined && node.change !== 'removed')
      detail.append(button('查看此成员的复杂度', () => showMetrics(node.member)))
    const versions =
      node.change === 'removed' && graph.document.baseline !== undefined
        ? graph.document.baseline
        : graph.document.current
    const members =
      node.member === undefined ? [] : versions.members.filter(item => item.path === node.member)
    for (const member of members)
      detail.append(
        element(
          'p',
          `清单来源 ${member.manifest.path} · ${member.category} · TS 源 ${member.sources.length} · 数据文件 ${member.dataFiles.length}`,
        ),
      )
    const facts = versions.facts.filter(fact =>
      node.member === undefined ? fact.key === node.label : fact.member === node.member,
    )
    for (const fact of facts)
      detail.append(
        element(
          'p',
          `${fact.kind} · ${fact.key} · 插件 ${fact.plugin ?? '未标识'} · 作用域 ${fact.scope} · ${fact.path}:${fact.line}`,
        ),
      )
    if (node.kind === 'service') {
      const providers = versions.facts.filter(
        fact => fact.kind === 'provides' && fact.key === node.label,
      )
      detail.append(
        element('h3', `候选提供者 ${providers.length}`),
        element('p', '确认配置选择：未观测；实际运行绑定：未观测。'),
      )
      for (const fact of providers)
        detail.append(
          element('p', `${fact.member} · 插件 ${fact.plugin ?? '未标识'} · 作用域 ${fact.scope}`),
        )
    }
  }
  function showEdge(edge: ViewEdge): void {
    detail.replaceChildren(
      element('h2', graph.relations[edge.kind]),
      element(
        'p',
        `${nodeById.get(edge.from)?.member ?? nodeById.get(edge.from)?.label ?? edge.from} → ${nodeById.get(edge.to)?.member ?? nodeById.get(edge.to)?.label ?? edge.to} ${edge.label}`,
      ),
    )
    detail.append(
      element('p', '静态关系。装配声明表示源码候选条目；它不表示运维覆盖后的配置选择或已经运行。'),
    )
    for (const evidence of edge.evidence) {
      const commit = evidence.version === 'baseline' ? graph.baseline?.commit : graph.source.commit
      detail.append(
        element('h3', `${changeLabel[edge.change] || '当前关系'} · ${evidence.version} ${commit}`),
        element('code', evidence.id),
      )
      const ul = element('ul')
      for (const site of evidence.occurrences) {
        const extra =
          'kind' in site
            ? ` · ${site.kind} · 插件 ${site.plugin ?? '未标识'} · 作用域 ${site.scope} · 模式 ${site.mode ?? '未声明'}${site.expression === undefined ? '' : ' · ' + site.expression}`
            : ` · ${site.specifier} · ${site.symbol} · ${site.type ? '类型' : '运行'}`
        ul.append(element('li', `${site.path}:${site.line}${extra}`))
      }
      detail.append(ul)
    }
  }
  const nodeWidth = 270,
    nodeHeight = 84
  function edgeShape(
    edge: ViewEdge,
    positions: ReadonlyMap<string, { x: number; y: number }>,
  ): SVGElement {
    const from = positions.get(edge.from),
      to = positions.get(edge.to)
    if (from === undefined || to === undefined) throw new Error('Missing edge geometry')
    const sameColumn = from.x === to.x
    const right = from.x < to.x
    const x1 = sameColumn ? from.x + nodeWidth / 2 : from.x + (right ? nodeWidth : 0),
      y1 = from.y + (sameColumn ? nodeHeight : nodeHeight / 2),
      x2 = sameColumn ? to.x + nodeWidth / 2 : to.x + (right ? 0 : nodeWidth),
      y2 = to.y + (sameColumn ? 0 : nodeHeight / 2)
    const midX = (x1 + x2) / 2,
      midY = (y1 + y2) / 2
    const path = svgElement('path', {
      'data-edge-id': edge.id,
      d: sameColumn
        ? `M${x1},${y1} C${x1},${midY} ${x2},${midY} ${x2},${y2}`
        : `M${x1},${y1} C${midX},${y1} ${midX},${y2} ${x2},${y2}`,
      fill: 'none',
      stroke:
        edge.change === 'added' ? '#1f6feb' : edge.change === 'removed' ? '#b7473d' : '#9aa0a6',
      'stroke-width': '1.2',
      'stroke-opacity': '0.6',
      'stroke-dasharray':
        edge.kind === 'type-import' || edge.kind === 'optional' || edge.change === 'removed'
          ? '5 4'
          : '',
      'marker-end': 'url(#arch-arrow)',
    })
    path.append(svgElement('title', {}, `${graph.relations[edge.kind]} ${edge.label}`))
    return path
  }
  function nodeShape(
    node: ViewNode,
    positions: ReadonlyMap<string, { x: number; y: number }>,
  ): SVGElement {
    const at = positions.get(node.id)
    if (at === undefined) throw new Error('Missing node geometry')
    const g = svgElement('g', {
      role: 'button',
      tabindex: '0',
      'aria-label': node.member ?? node.label,
      'data-node-id': node.id,
      transform: `translate(${at.x},${at.y})`,
    })
    const fills = { green: '#dcefdc', yellow: '#fbeebf', red: '#f8d2cf' }
    const fill =
      complexity.checked && node.complexity !== undefined && node.complexity.functions > 0
        ? fills[node.complexity.band]
        : node.kind === 'service'
          ? '#e6eefb'
          : node.kind === 'event'
            ? '#f2e8fb'
            : '#f5f5f1'
    g.append(
      svgElement('rect', {
        width: String(nodeWidth),
        height: String(nodeHeight),
        rx: '4',
        fill,
        stroke:
          node.change === 'added'
            ? '#1f6feb'
            : node.change === 'removed'
              ? '#b7473d'
              : node.id === focus.value
                ? '#1f6feb'
                : '#6b7280',
        'stroke-width': node.change === 'present' ? '1' : '3',
        'stroke-dasharray': node.change === 'removed' ? '5 4' : '',
      }),
    )
    const title = node.member?.split('/').pop() ?? node.label
    g.append(
      svgElement(
        'text',
        { x: '10', y: '18', fill: '#4b5563', 'font-size': '11' },
        `«${nodeKind(node)}» ${changeLabel[node.change]}`,
      ),
      svgElement(
        'text',
        { x: '10', y: '40', fill: '#1d1f21', 'font-size': '13' },
        title.length > 34 ? title.slice(0, 31) + '…' : title,
      ),
    )
    const annotations = [
      node.kind === 'group' ? `${node.count ?? 0} 个当前成员` : '',
      complexity.checked && node.complexity !== undefined
        ? node.complexity.functions === 0
          ? '无函数'
          : `CC 最大 ${node.complexity.max} / 风险 ${node.complexity.risk.toFixed(1)}`
        : '',
      coupling.checked ? `入 ${node.fanIn ?? 0} / 出 ${node.fanOut ?? 0}` : '',
    ].filter(Boolean)
    g.append(
      svgElement(
        'text',
        { x: '10', y: '67', fill: '#4b5563', 'font-size': '11' },
        annotations.join(' · '),
      ),
      svgElement('title', {}, node.member ?? node.label),
    )
    g.addEventListener('click', () => focusNode(node))
    g.addEventListener('keydown', event => {
      if (event instanceof KeyboardEvent && ['Enter', ' '].includes(event.key)) {
        event.preventDefault()
        focusNode(node)
      }
    })
    return g
  }
  function drawDiagram(): void {
    const columns = 4,
      width = 1160,
      rowHeight = 112
    const positions = new Map<string, { x: number; y: number }>()
    const occupied = [0, 0, 0, 0]
    for (const [index, node] of shown.nodes.entries()) {
      const primary = node.id === focus.value || (focus.value === '' && node.group === group.value)
      const column = shown.overview
        ? index % columns
        : primary
          ? 0
          : ['service', 'event'].includes(node.kind)
            ? 1
            : node.kind === 'member'
              ? 2
              : 3
      const row = shown.overview ? Math.floor(index / columns) : (occupied[column] ?? 0)
      positions.set(node.id, { x: 10 + column * 286, y: 10 + row * rowHeight })
      occupied[column] = row + 1
    }
    const height = Math.max(rowHeight, Math.max(...occupied) * rowHeight + 20)
    const svg = svgElement('svg', {
      xmlns: 'http://www.w3.org/2000/svg',
      viewBox: `0 0 ${width} ${height}`,
      role: 'img',
      'aria-label': shown.overview ? '系统总览图' : '当前架构子图',
      width: String(width),
      height: String(height),
    })
    const defs = svgElement('defs', {})
    const marker = svgElement('marker', {
      id: 'arch-arrow',
      viewBox: '0 0 8 8',
      refX: '7',
      refY: '4',
      markerWidth: '7',
      markerHeight: '7',
      orient: 'auto',
    })
    marker.append(svgElement('path', { d: 'M0,0 L8,4 L0,8 z', fill: 'context-stroke' }))
    defs.append(marker)
    svg.append(defs)
    const paths = svgElement('g', {})
    for (const edge of shown.edges) paths.append(edgeShape(edge, positions))
    svg.append(paths)
    for (const node of shown.nodes) svg.append(nodeShape(node, positions))
    diagram.replaceChildren(svg)
  }
  function renderOverview(): void {
    const cards = required('arch-overview')
    cards.replaceChildren()
    for (const node of shown.nodes) {
      const card = button(
        `${node.label} · ${node.count ?? 0} 个当前成员${node.change === 'removed' ? ' · 已删除' : ''}`,
        () => focusNode(node),
      )
      card.className = 'arch-card'
      cards.append(card)
    }
    cards.hidden = !shown.overview
  }
  function renderRelations(): void {
    list.replaceChildren(
      element('h2', `当前选择：${shown.nodes.length} 个节点 · ${shown.edges.length} 条聚合关系`),
    )
    if (shown.overview) {
      list.append(element('p', '选择应用或目录组展开。总览不画全包箭头；导出保留当前总览。'))
      return
    }
    if (shown.nodes.length === 0)
      list.append(element('p', '当前选择没有节点；这不表示全系统没有关系。'))
    for (const edge of shown.edges) {
      const from = nodeById.get(edge.from),
        to = nodeById.get(edge.to)
      const text = `${changeLabel[edge.change]} ${graph.relations[edge.kind]} · ${from?.member ?? from?.label} → ${to?.member ?? to?.label} ${edge.label} · ${edge.evidence.length} 条事实`
      const row = button(text, () => showEdge(edge))
      row.className = 'arch-edge'
      row.setAttribute('data-edge-id', edge.id)
      list.append(row)
    }
  }
  function render(): void {
    shown = selectView(graph, selection())
    drawDiagram()
    renderOverview()
    renderRelations()
    detail.replaceChildren(element('p', '点击节点查看声明，点击关系查看全部出处。'))
  }
  function renderUnknowns(): void {
    const container = required('arch-unknown')
    container.replaceChildren()
    const append = (value: ArchitectureView['document']['current'], version: string): void => {
      for (const item of value.unknown) {
        const ul = element('ul')
        for (const site of item.occurrences)
          ul.append(
            element(
              'li',
              `${version} ${value.source.commit} · ${site.member} · ${site.path}:${site.line} · ${site.kind} · ${site.expression} · ${site.reason}`,
            ),
          )
        container.append(ul)
      }
    }
    append(graph.document.current, 'current')
    if (graph.document.baseline !== undefined) append(graph.document.baseline, 'baseline')
    if (graph.document.current.unknown.length === 0)
      container.append(element('p', '没有记录到具体 unknown；未识别写法仍可能漏检。'))
    container.append(
      element(
        'p',
        'unknown 的条数不是全部架构缺口。进程、外部资源、运维最终配置和实际运行绑定未观测。',
      ),
      element(
        'p',
        '架构预期与规划：未提供；符合性尚未判定。生命周期、租户隔离、事务和恢复需要行为证据。',
      ),
    )
    for (const limitation of graph.document.current.scope.limitations)
      container.append(element('p', limitation))
  }
  for (const control of [group, focus, changes, neighbors, complexity, coupling])
    control.addEventListener('change', render)
  required('arch-home').addEventListener('click', () => {
    group.value = ''
    focus.value = ''
    render()
  })
  required('arch-tab').addEventListener('click', showArchitecture)
  required('metrics-tab').addEventListener('click', () => showMetrics())
  required('arch-export-json').addEventListener('click', () =>
    download(
      'architecture-selection.json',
      JSON.stringify(shown, null, 2) + '\n',
      'application/json',
    ),
  )
  required('arch-export-svg').addEventListener('click', () => {
    const svg = diagram.querySelector('svg')
    if (svg === null) throw new Error('No diagram to export')
    download(
      'architecture-selection.svg',
      new XMLSerializer().serializeToString(svg),
      'image/svg+xml',
    )
  })
  required('arch-guidance').append(
    element(
      'p',
      '六问导航：①总览看应用与目录组；②装配声明看源码候选，最终配置与运行状态未观测；③运行/类型导入看直接耦合；④服务与事件筛选看静态连接；⑤变化范围看新增删除，架构预期未提供；⑥叠加耦合与圈复杂度，或进入复杂度与风险查看环和热点。',
    ),
  )
  renderUnknowns()
  render()
  const initialMember = decodeURIComponent(location.hash.slice(1))
  if (graph.nodes.some(node => node.member === initialMember)) showMetrics(initialMember)
}
