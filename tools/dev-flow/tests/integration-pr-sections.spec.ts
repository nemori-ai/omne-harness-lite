import { describe, expect, it } from 'vitest'
import { CARDS_SECTION, formatCardLine, parsePullSections } from '../src/integration/pr-sections.ts'

/**
 * The card line template of `gate/README.md`「提升 PR 的说明」 on `github-gate`
 * (25aa4702e1c9e0f36081060c417c71af7b572501), copied byte for byte.
 */
const GATE_TEMPLATE =
  '- #<Issue 编号> revision <交付修订> attempt `<attempt>`：<这张卡在上一层或 main 上要满足的条件，没有写“无”>'
/** The template as a pattern: numbers for the two numeric slots, nonempty text elsewhere. */
const gateLine = new RegExp(
  `^${GATE_TEMPLATE.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    .replace('<Issue 编号>', '[1-9][0-9]*')
    .replace('<交付修订>', '[1-9][0-9]*')
    .replace('<attempt>', '[^`\\s]+')
    .replace(/<[^>]+>$/, '\\S.*')}$`,
)

function body(cards: string[] | null, contracts: string[] | null = ['无']): string {
  return [
    '## 能力与结果',
    '',
    '正文。',
    ...(cards === null ? [] : ['', `## ${CARDS_SECTION}`, '', '<!-- 模板提示 -->', ...cards]),
    ...(contracts === null ? [] : ['', '## 契约变化', '', ...contracts]),
    '',
    '---',
    '_Generated by host_',
  ].join('\n')
}

describe('PR sections', () => {
  it('formats a card line in the gate README format', () => {
    const line = formatCardLine({ issue: 12, revision: 3, attempt: 'a-b_c.1', condition: '无' })
    expect(line).toMatch(gateLine)
    // The pattern derived from the template is strict: a comma separator does not pass.
    expect('- #8 revision 2 attempt `8-a2`，无').not.toMatch(gateLine)
  })
  it('reads backticked contract paths and ignores prose lines', () => {
    const sections = parsePullSections(
      body(
        ['说明文字。', '- #7 revision 1 attempt `7-a1`：无'],
        ['以下按整张 PR 分类。', '- `packages/model/model-contract`：additive。新增导出 X'],
      ),
    )
    expect(sections.cards).toEqual({
      kind: 'listed',
      entries: [{ issue: 7, revision: 1, attempt: '7-a1', condition: '无' }],
      invalid: [],
    })
    expect(sections.contracts).toEqual({
      kind: 'listed',
      entries: [{ path: 'packages/model/model-contract', level: 'additive', note: '新增导出 X' }],
      invalid: [],
    })
  })
  it('reads「无」 when a footer without a thematic break follows it', () => {
    const sections = parsePullSections(
      '## 契约变化\n\n无\n\n_Generated by [Claude Code](https://claude.ai/code)_\n',
    )
    expect(sections.contracts).toEqual({ kind: 'none' })
  })
  it('does not read「无」 when the section also has an indented or quoted list line', () => {
    for (const line of [
      '  - packages/model/model-contract：additive',
      '   - packages/model/model-contract：additive',
      '> - packages/model/model-contract：breaking',
    ])
      expect(parsePullSections(`## 契约变化\n\n无\n\n${line}\n`).contracts).toEqual({
        kind: 'empty',
      })
  })
  it('ignores fenced code and nested items, and reads every occurrence of a section', () => {
    const sections = parsePullSections(
      [
        '## 所含的卡',
        '',
        '```text',
        '- #1 revision 1 attempt `template`：无',
        '```',
        '- #7 revision 1 attempt `7-a1`：无',
        '  - #8 revision 1 attempt `nested`：说明',
        '',
        '## 其他',
        '',
        '- #9 revision 1 attempt `other-section`：无',
        '',
        '## 所含的卡',
        '',
        '- #10 revision 2 attempt `10-a1`：无',
      ].join('\n'),
    )
    expect(sections.cards).toEqual({
      kind: 'listed',
      entries: [
        { issue: 7, revision: 1, attempt: '7-a1', condition: '无' },
        { issue: 10, revision: 2, attempt: '10-a1', condition: '无' },
      ],
      invalid: [],
    })
  })
  it('counts a contract line with other separators and reports it', () => {
    const sections = parsePullSections(
      body(
        ['- #7 revision 1 attempt `7-a1`：无'],
        [
          '- packages/model/model-contract：breaking（由 #8 承接）',
          '- packages/common/message（additive，新增 X）',
          '- 改了一些东西',
        ],
      ),
    )
    expect(sections.contracts).toEqual({
      kind: 'listed',
      entries: [
        { path: 'packages/model/model-contract', level: 'breaking', note: '（由 #8 承接）' },
        { path: 'packages/common/message', level: 'additive', note: '新增 X' },
      ],
      invalid: [
        { line: '- packages/common/message（additive，新增 X）', counted: true },
        { line: '- 改了一些东西', counted: false },
      ],
    })
  })
})
