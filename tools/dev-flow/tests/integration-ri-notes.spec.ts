/**
 * The card line template of `gate/README.md`「提升 PR 的说明」 on `github-gate`
 * (25aa4702e1c9e0f36081060c417c71af7b572501), copied byte for byte.
 */
const GATE_TEMPLATE =
  '- #<Issue 编号> revision <交付修订> attempt `<attempt>`：<这张卡在上一层或 main 上要满足的条件，没有写“无”>'
/** The template as a pattern: numbers for the two numeric slots, nonempty text elsewhere. */
const gateLine = new RegExp(
  `^${GATE_TEMPLATE.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    .replace('<Issue 编号>', '[1-9][0-9]*')
    .replace('<交付修订>', '[1-9][0-9]*')
    .replace('<attempt>', '[^`\\s]+')
    .replace(/<[^>]+>$/, '\\S.*')}$`,
)

const sha = (n: number) => n.toString(16).padStart(40, '0')
function unitCommit(n: number, pr: number, target = 'refs/heads/integration/legacy-refactor') {
  return {
    commit: sha(n),
    subject: `Merge pull request #${pr} from human/x`,
    coverage: 'checked',
    unit: { kind: 'found', record: { target, result: sha(n), pr } },
  } satisfies TrackCommit
}
function body(cards: string[] | null, contracts: string[] | null = ['无']): string {
  return [
    '## 能力与结果',
    '',
    '正文。',
    ...(cards === null ? [] : ['', `## ${CARDS_SECTION}`, '', '<!-- 模板提示 -->', ...cards]),
    ...(contracts === null ? [] : ['', '## 契约变化', '', ...contracts]),
    '',
    '---',
    '_Generated by host_',
  ].join('\n')
}
type CardSpec = { line?: string; nature?: string; change?: string; binding?: [number, string] }
function card(n: number, spec: CardSpec): CardRead {
  const fields = [
    spec.line === undefined ? [] : [`- 交付线：${spec.line}`],
    spec.nature === undefined ? [] : [`- 性质：${spec.nature}`],
    spec.change === undefined ? [] : [`- 契约变更：${spec.change}`],
  ].flat()
  const url = `https://github.com/owner/repo/issues/${n}`
  return {
    kind: 'read',
    card: {
      url,
      binding:
        spec.binding === undefined
          ? undefined
          : { revision: spec.binding[0], attempt: spec.binding[1] },
      attributes: readCardAttributes(['## 身份与责任', '', ...fields].join('\n'), {
        url,
        labels: [],
        milestone: 'M1',
      }),
    },
  }
}
function input({
  track = 'legacy-refactor',
  commits,
  pulls,
  cards = {},
  contractDiff = { kind: 'unavailable', reason: 'P1-2 not wired' },
}: {
  track?: string
  commits: TrackCommit[]
  pulls: Record<number, Omit<PullFact, 'number' | 'url'>>
  cards?: Record<number, CardSpec>
  contractDiff?: ContractDiff
}): RiInput {
  const t = registeredTrack(registry, track)
  return {
    repository: 'owner/repo',
    track: t,
    parent: {
      name: t.parent,
      branch: t.parent === 'main' ? 'main' : `integration/${t.parent}`,
      head: sha(9999),
    },
    head: commits.at(-1)?.commit ?? sha(9999),
    lowerBound: { commit: sha(1), source: 'cutover' },
    commits,
    lines: table(),
    registry,
    readPull: n => {
      const pull = pulls[n]
      return pull === undefined
        ? { kind: 'unreadable', reason: 'not found' }
        : {
            kind: 'read',
            pull: { number: n, url: `https://github.com/owner/repo/pull/${n}`, ...pull },
          }
    },
    readCard: n => {
      const spec = cards[n]
      return spec === undefined ? { kind: 'unreadable', reason: 'not found' } : card(n, spec)
    },
    contractDiff,
  }
}
const work = (b: string, base = 'integration/legacy-refactor') => ({
  headRef: 'human/issue-7-x',
  baseRef: base,
  body: b,
})
const toolchain: CardSpec = { line: 'engineering-toolchain', nature: 'impl', change: 'none' }
function codes(notes: ReturnType<typeof riNotes>) {
  return notes.findings.map(finding => finding.code)
}

describe('ri-notes sections', () => {
  it('writes every card line in the gate README format and ends the sections at the footer', () => {
    const notes = riNotes(
      input({
        commits: [unitCommit(2, 10), unitCommit(3, 11)],
        pulls: {
          10: work(body(['- #7 revision 1 attempt `7-a1`：无'])),
          11: work(body(['- #8 revision 2 attempt `8-a2`：进入 main 前须 #9 被接受'])),
        },
        cards: { 7: toolchain, 8: toolchain },
      }),
    )
    const section = notes.markdown
      .split('## 契约变化')[0]
      ?.split('\n')
      .filter(l => l.startsWith('- '))
    expect(section).toEqual([
      '- #7 revision 1 attempt `7-a1`：无',
      '- #8 revision 2 attempt `8-a2`：进入 main 前须 #9 被接受',
    ])
    for (const line of section ?? []) expect(line).toMatch(gateLine)
    // The pattern derived from the template is strict: a comma separator does not pass.
    expect('- #8 revision 2 attempt `8-a2`，无').not.toMatch(gateLine)
    expect(notes.markdown).toContain('## 契约变化\n\n无\n')
    expect(notes.findings).toEqual([])
  })
  it('keeps the gate format for inferred and repaired lines', () => {
    const lines = [
      formatCardLine({ issue: 12, revision: 3, attempt: 'a-b_c.1', condition: '无' }),
      ...riNotes(
        input({
          commits: [unitCommit(2, 10), unitCommit(3, 11)],
          pulls: {
            10: work(body(null)),
            11: work(body(['- #8 revision 2 attempt `8-a2`，taskBase 已核'])),
          },
          cards: { 7: { ...toolchain, binding: [4, '7-a4'] }, 8: toolchain },
        }),
      )
        .markdown.split('\n')
        .filter(line => line.startsWith('- #')),
    ]
    expect(lines).toHaveLength(3)
    for (const line of lines) expect(line).toMatch(gateLine)
  })
  it('reads backticked contract paths and ignores prose lines', () => {
    const sections = parsePullSections(
      body(
        ['说明文字。', '- #7 revision 1 attempt `7-a1`：无'],
        ['以下按整张 PR 分类。', '- `packages/model/model-contract`：additive。新增导出 X'],
      ),
    )
    expect(sections.cards).toEqual({
      kind: 'present',
      entries: [{ issue: 7, revision: 1, attempt: '7-a1', condition: '无' }],
      invalid: [],
    })
    expect(sections.contracts).toEqual({
      kind: 'present',
      entries: [{ path: 'packages/model/model-contract', level: 'additive', note: '新增导出 X' }],
      invalid: [],
    })
  })
})

describe('ri-notes aggregation', () => {
  it('takes the latest revision and, within it, the latest attempt of each card', () => {
    const notes = riNotes(
      input({
        commits: [unitCommit(2, 10), unitCommit(3, 11), unitCommit(4, 12), unitCommit(5, 13)],
        pulls: {
          10: work(body(['- #7 revision 2 attempt `7-r2-a1`：旧'])),
          11: work(body(['- #7 revision 2 attempt `7-r2-a2`：新'])),
          12: work(body(['- #7 revision 1 attempt `7-r1-a9`：更旧的修订'])),
          13: { headRef: 'main', baseRef: 'integration/legacy-refactor', body: '同步' },
        },
        cards: { 7: toolchain },
      }),
    )
    expect(notes.cards.map(c => [c.issue, c.revision, c.attempt, c.condition, c.pulls])).toEqual([
      [7, 2, '7-r2-a2', '新', [10, 11, 12]],
    ])
    expect(notes.commits.map(c => c.pr?.kind)).toEqual(['work', 'work', 'work', 'sync'])
    expect(notes.findings).toEqual([])
  })
  it('lists every commit with its unit and PR, and the promotion of a child track', () => {
    const notes = riNotes(
      input({
        commits: [
          {
            commit: sha(1),
            subject: 'before cutover',
            coverage: 'before-lower-bound',
            unit: { kind: 'missing' },
          },
          unitCommit(2, 10),
        ],
        pulls: {
          10: {
            headRef: 'integration/model',
            baseRef: 'integration/legacy-refactor',
            body: body(['- #20 revision 1 attempt `20-a1`：无']),
          },
        },
        cards: { 20: { line: 'model', nature: 'impl', change: 'none' } },
      }),
    )
    expect(notes.commits).toEqual([
      {
        commit: sha(1),
        subject: 'before cutover',
        coverage: 'before-lower-bound',
        unit: 'missing',
        pr: null,
      },
      {
        commit: sha(2),
        subject: 'Merge pull request #10 from human/x',
        coverage: 'checked',
        unit: 'found',
        pr: {
          number: 10,
          source: 'unit',
          url: 'https://github.com/owner/repo/pull/10',
          kind: 'promote',
        },
      },
    ])
    // A model-line card reaches the integration track through its line track: no finding.
    expect(notes.findings).toEqual([])
  })
  it('merges contract changes to the highest level per member with their notes', () => {
    const notes = riNotes(
      input({
        commits: [unitCommit(2, 10), unitCommit(3, 11)],
        pulls: {
          10: work(
            body(
              ['- #7 revision 1 attempt `7-a1`：无'],
              ['- packages/model/model-contract：additive。新增 X'],
            ),
          ),
          11: work(
            body(
              ['- #8 revision 1 attempt `8-a1`：无'],
              ['- packages/model/model-contract：breaking。由 #8 承接'],
            ),
          ),
        },
        cards: {
          7: { line: 'model', nature: 'impl', change: 'additive' },
          8: { line: 'integration', nature: 'integration', change: 'breaking' },
        },
      }),
    )
    expect(notes.markdown).toContain(
      '## 契约变化\n\n- packages/model/model-contract：breaking。#10：新增 X；#11：由 #8 承接\n',
    )
    expect(notes.findings).toEqual([])
  })
})

describe('ri-notes findings', () => {
  it('reports a PR without the two sections and infers its card from the branch', () => {
    const notes = riNotes(
      input({
        commits: [unitCommit(2, 10)],
        pulls: { 10: work(body(null, null)) },
        cards: { 7: { ...toolchain, binding: [3, '7-a3'] } },
      }),
    )
    expect(notes.findings.filter(f => f.code === 'pr-section-missing')).toEqual([
      expect.objectContaining({
        at: expect.objectContaining({
          pr: 'https://github.com/owner/repo/pull/10',
          commit: sha(2),
          section: '所含的卡',
        }),
      }),
      expect.objectContaining({
        at: expect.objectContaining({
          pr: 'https://github.com/owner/repo/pull/10',
          section: '契约变化',
        }),
      }),
    ])
    expect(codes(notes)).toContain('card-inferred')
    expect(notes.cards).toEqual([
      expect.objectContaining({ issue: 7, revision: 3, attempt: '7-a3', inferred: true }),
    ])
  })
  it('infers the card when no line of「所含的卡」can be read', () => {
    const notes = riNotes(
      input({
        commits: [unitCommit(2, 10)],
        pulls: { 10: work(body(['- #7 issuecomment-1'])) },
        cards: { 7: { ...toolchain, binding: [2, '7-a2'] } },
      }),
    )
    expect(codes(notes)).toEqual(['cards-line-invalid', 'card-inferred'])
    expect(notes.cards).toEqual([
      expect.objectContaining({ issue: 7, revision: 2, attempt: '7-a2', inferred: true }),
    ])
  })
  it('reports a missing unit record at its commit, and only after the lower bound', () => {
    const notes = riNotes(
      input({
        commits: [
          {
            commit: sha(1),
            subject: 'old push',
            coverage: 'before-lower-bound',
            unit: { kind: 'missing' },
          },
          {
            commit: sha(2),
            subject: 'direct push',
            coverage: 'checked',
            unit: { kind: 'missing' },
          },
        ],
        pulls: {},
      }),
    )
    expect(notes.findings.filter(f => f.code === 'unit-missing')).toEqual([
      {
        severity: 'report',
        code: 'unit-missing',
        at: { commit: sha(2) },
        message: expect.stringContaining('direct push'),
      },
    ])
  })
  it('reports a card of another line whose line is not integration', () => {
    const notes = riNotes(
      input({
        track: 'model',
        commits: [unitCommit(2, 10, 'refs/heads/integration/model')],
        pulls: {
          10: work(
            body([
              '- #20 revision 1 attempt `20-a1`：无',
              '- #21 revision 1 attempt `21-a1`：无',
              '- #22 revision 1 attempt `22-a1`：无',
            ]),
            'integration/model',
          ),
        },
        cards: {
          20: { line: 'model', nature: 'impl', change: 'none' },
          21: { line: 'session-agent', nature: 'impl', change: 'none' },
          22: { line: 'integration', nature: 'integration', change: 'none' },
        },
      }),
    )
    expect(notes.findings).toEqual([
      {
        severity: 'report',
        code: 'card-other-line',
        at: { issue: 'https://github.com/owner/repo/issues/21' },
        message: expect.stringContaining('session-agent'),
      },
    ])
  })
  it('reports unit, PR and declaration defects where they occur', () => {
    const notes = riNotes(
      input({
        commits: [
          unitCommit(2, 10, 'refs/heads/main'),
          unitCommit(3, 11),
          {
            commit: sha(4),
            subject: 'x',
            coverage: 'checked',
            unit: { kind: 'invalid', reason: 'not JSON' },
          },
        ],
        pulls: {
          10: work(
            body(
              ['- #7 revision 1 attempt `7-a1`：无', '- #7 无格式'],
              ['- packages/nope：additive'],
            ),
            'main',
          ),
        },
        cards: { 7: { line: 'model', nature: 'impl', change: 'none' } },
      }),
    )
    expect(codes(notes).sort()).toEqual(
      [
        'cards-line-invalid',
        'contract-level-exceeds-card',
        'contract-path-unknown',
        'pr-base-mismatch',
        'pr-unreadable',
        'unit-invalid',
        'unit-target-mismatch',
      ].sort(),
    )
  })
})

describe('ri-notes contract check seam (C4 before P1-2)', () => {
  const pulls = {
    10: work(
      body(['- #7 revision 1 attempt `7-a1`：无'], ['- packages/model/model-contract：additive']),
    ),
  }
  const cards = { 7: { line: 'model', nature: 'impl', change: 'additive' } }
  it('says the check did not run while no snapshot difference is wired', () => {
    const notes = riNotes(input({ commits: [unitCommit(2, 10)], pulls, cards }))
    expect(notes.contractCheck).toEqual({ status: 'unavailable', reason: 'P1-2 not wired' })
  })
  it('compares a supplied difference with the declarations, review matching only breaking', () => {
    const notes = riNotes(
      input({
        commits: [unitCommit(2, 10)],
        pulls,
        cards,
        contractDiff: {
          kind: 'available',
          base: sha(1),
          head: sha(2),
          members: [
            { path: 'packages/model/model-contract', level: 'review' },
            { path: 'packages/common/message', level: 'additive' },
          ],
        },
      }),
    )
    expect(notes.contractCheck).toEqual({ status: 'checked', base: sha(1), head: sha(2) })
    expect(notes.findings.map(f => [f.code, f.at.path])).toEqual([
      ['contract-diff-mismatch', 'packages/common/message'],
      ['contract-diff-mismatch', 'packages/model/model-contract'],
    ])
  })
})
