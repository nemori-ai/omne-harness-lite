function turned(points: readonly Point[], degrees: number, [ox, oy]: Point): Point[] {
  const [cos, sin] = [Math.cos((degrees * Math.PI) / 180), Math.sin((degrees * Math.PI) / 180)]
  return points.map(
    ([x, y]) =>
      [ox + (x - ox) * cos - (y - oy) * sin, oy + (x - ox) * sin + (y - oy) * cos] as const,
  )
}
